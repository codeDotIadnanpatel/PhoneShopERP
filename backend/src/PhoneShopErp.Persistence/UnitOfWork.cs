using Npgsql;

namespace PhoneShopErp.Persistence;

/// <summary>
/// PostgreSQL setting names used for transaction-local context. They are set
/// with <c>set_config(name, value, true)</c> and therefore disappear when the
/// transaction ends; a pooled connection can never carry tenant context into the
/// next request (ADR-0012).
/// </summary>
public static class PostgresContextSettings
{
    public const string TenantId = "app.tenant_id";
    public const string UserId = "app.user_id";
    public const string SessionId = "app.session_id";
    public const string SessionReference = "app.session_reference";
    public const string Subject = "app.subject";
}

/// <summary>
/// The authenticated but not-yet-tenant-scoped context. It exists only for the
/// two approved pre-tenant read paths: resolving the caller's own user row, own
/// memberships and own session. It never grants access to business data.
/// </summary>
public sealed record PreTenantContext(string Subject, Guid? UserId, string? SessionReference = null)
{
    public static PreTenantContext ForSubject(string subject) =>
        new(ValidateSubject(subject), null, null);

    public static PreTenantContext ForUser(
        string subject,
        Guid userId,
        string? sessionReference = null) =>
        new(ValidateSubject(subject), RequireId(userId), sessionReference);

    private static string ValidateSubject(string subject)
    {
        if (string.IsNullOrWhiteSpace(subject) || subject.Length > 255)
        {
            throw new ArgumentException(
                "Subject must be a non-empty string of at most 255 characters.",
                nameof(subject));
        }

        return subject;
    }

    private static Guid RequireId(Guid value) =>
        value == Guid.Empty
            ? throw new ArgumentException("Identifier must not be empty.", nameof(value))
            : value;
}

public interface IUnitOfWork : IAsyncDisposable
{
    NpgsqlConnection Connection { get; }

    NpgsqlTransaction Transaction { get; }

    bool IsCompleted { get; }

    /// <summary>
    /// Establishes tenant context inside an already-open pre-tenant transaction.
    /// This exists for exactly one flow: onboarding, where the tenant identifier
    /// is generated by the server and the caller has no membership yet. The
    /// identifiers must come from server-side state, never from a request body,
    /// header, query string or token claim.
    /// </summary>
    Task ApplyTenantContextAsync(
        Guid tenantId,
        Guid userId,
        CancellationToken cancellationToken);

    Task CommitAsync(CancellationToken cancellationToken);

    Task RollbackAsync(CancellationToken cancellationToken);
}

public interface ITenantUnitOfWorkFactory
{
    Task<IUnitOfWork> BeginAsync(
        PhoneShopErp.Platform.Tenancy.TenantContext context,
        CancellationToken cancellationToken);
}

public interface IPreTenantUnitOfWorkFactory
{
    Task<IUnitOfWork> BeginAsync(PreTenantContext context, CancellationToken cancellationToken);
}
